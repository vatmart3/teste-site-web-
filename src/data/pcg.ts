/** Normalise pour la recherche : minuscules, sans accents, sans ponctuation. */
export function normaliser(s: string): string {
  return s
    .toLowerCase()
    .normalize('NFD')
    .replace(/[\u0300-\u036f]/g, '')
    .replace(/['’\-,.()]/g, ' ')
    .replace(/\s+/g, ' ')
    .trim()
}

const INDEX = COMPTES.map((c) => ({
  compte: c,
  cle: normaliser([c.numero, c.intitule, ...c.alias].join(' ')),
}))

export function chercherComptes(requete: string, classe: number | null = null): Compte[] {
  const q = normaliser(requete)
  const base = classe ? INDEX.filter((e) => e.compte.classe === classe) : INDEX
  if (!q) return base.map((e) => e.compte)
  const mots = q.split(' ')
  return base
    .filter((e) => mots.every((m) => e.cle.includes(m)))
    .sort((a, b) => {
      // Priorité au préfixe de numéro, puis au numéro le plus court.
      const pa = a.compte.numero.startsWith(q) ? 0 : 1
      const pb = b.compte.numero.startsWith(q) ? 0 : 1
      if (pa !== pb) return pa - pb
      return a.compte.numero.localeCompare(b.compte.numero)
    })
    .map((e) => e.compte)
}

export function trouverCompte(numero: string): Compte | undefined {
  return COMPTES.find((c) => c.numero === numero)
}
